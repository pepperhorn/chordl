"""Regenerates src/poppins-metrics.ts from the Poppins TTFs chordcards prints with.

    python3 -m pip install fonttools
    python3 scripts/poppins-metrics.py /path/to/chordcards/assets/fonts > src/poppins-metrics.ts

Poppins carries no Latin kerning (its GPOS holds Devanagari marks only), so a
run's advance is exactly the sum of its glyphs' advances. @fontsource/poppins
(the site's copy) has identical advances for every printable ASCII character.
"""
import json
import sys
from fontTools.ttLib import TTFont

fonts = sys.argv[1]
CHARS = "".join(chr(c) for c in range(32, 127)) + "°ø"
print("// Generated by scripts/poppins-metrics.py from Poppins 4.004 — do not edit by hand.")
print("// Advance widths in font units (unitsPerEm 1000), keyed by weight.\n")
print("export const POPPINS_CHARS = " + json.dumps(CHARS, ensure_ascii=False) + ";\n")
print("export const POPPINS_ADVANCES: Record<400 | 600 | 700, readonly number[]> = {")
for w, n in [(400, "Regular"), (600, "SemiBold"), (700, "Bold")]:
    f = TTFont(f"{fonts}/Poppins-{n}.ttf")
    cmap = f.getBestCmap()
    adv = [f["hmtx"][cmap[ord(c)]][0] for c in CHARS]
    print(f"  {w}: [{', '.join(map(str, adv))}],")
print("};")
